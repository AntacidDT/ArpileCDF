void lcd_text_putc(ili9488_t *dev, uint16_t x, uint16_t y, char c,
                   uint16_t fg, uint16_t bg)
{
    if (c < 0x20 || c > 0x7E) {
        return;
    }
    const uint8_t *g = font5x7[c - 0x20];
    for (int row = 0; row < 7; row++) {
        for (int col = 0; col < 5; col++) {
            uint16_t color = (g[row] & (0x10 >> col)) ? fg : bg;
            ili9488_fill_rect(dev, x + col, y + row, 1, 1, color);
        }
    }
}

uint16_t lcd_text_puts(ili9488_t *dev, uint16_t x, uint16_t y, const char *s,
                       uint16_t fg, uint16_t bg)
{
    uint16_t cx = x;
    while (*s) {
        lcd_text_putc(dev, cx, y, *s, fg, bg);
        cx += LCD_TEXT_CHAR_W;
        s++;
    }
    return cx;
}